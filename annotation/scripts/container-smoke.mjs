async function api(path, body, method = 'POST') {
  const result = await request(base + '/api/annotation' + path, { method, headers: { ...headers, cookie }, ...(method === 'GET' ? {} : { body: JSON.stringify(body ?? {}) }) });
  return { status: result.status, value: JSON.parse(await result.text()) };
}
